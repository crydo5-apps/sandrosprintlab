package com.example.service.slicer

import com.example.model.GcodeResult
import com.example.model.Mesh3D
import com.example.model.SlicingConfig
import kotlinx.coroutines.delay
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.flow
import kotlin.math.ceil
import kotlin.math.hypot

sealed class SlicingProgress {
    data class Progress(val percentage: Int, val currentPhase: String) : SlicingProgress()
    data class Completed(val result: GcodeResult) : SlicingProgress()
    data class Error(val message: String) : SlicingProgress()
}

interface SlicerEngine {
    val engineName: String
    fun slice(mesh: Mesh3D, config: SlicingConfig): Flow<SlicingProgress>
}

class CrealityCR10SProSlicer : SlicerEngine {
    override val engineName: String = "Creality CR-10S Pro Native Slicer v2.4 (Marlin/Cura compatible)"

    override fun slice(mesh: Mesh3D, config: SlicingConfig): Flow<SlicingProgress> = flow {
        // Pre-slice validation
        if (!mesh.fitsInCr10SPro()) {
            emit(SlicingProgress.Error("Modell überschreitet das CR-10S Pro Druckvolumen von 300x300x400 mm! Bitte herunterskalieren."))
            return@flow
        }

        if (config.nozzleTempC < 170) {
            emit(SlicingProgress.Error("Düsentemperatur (${config.nozzleTempC}°C) ist zu niedrig für Schmelzextrusion."))
            return@flow
        }

        emit(SlicingProgress.Progress(5, "Geometrie vorbereiten & Bounding-Box prüfen..."))
        delay(300)

        emit(SlicingProgress.Progress(20, "Schichten schneiden (Layer Height: ${config.layerHeightMm} mm)..."))
        delay(400)

        emit(SlicingProgress.Progress(45, "Perimeter & Wandpfade berechnen (Düse: ${config.nozzleDiameterMm} mm)..."))
        delay(400)

        emit(SlicingProgress.Progress(65, "Infill generieren (${config.infillPattern.displayName}, ${config.infillDensityPercent}%)..."))
        delay(400)

        emit(SlicingProgress.Progress(80, "CR-10S Pro Start-/End-Code & Retraction (${config.retractionDistanceMm}mm @ ${config.retractionSpeedMmS}mm/s)..."))
        delay(350)

        emit(SlicingProgress.Progress(95, "G-Code formatieren & Flussraten validieren..."))
        delay(300)

        // Generate genuine structured G-code for Creality CR-10S Pro
        val totalLayers = ceil(mesh.sizeZ / config.layerHeightMm).toInt().coerceAtLeast(1)
        val gcodeText = generateFullGcode(mesh, config, totalLayers)

        val filamentUsageMeters = (mesh.volumeCm3 * (config.infillDensityPercent / 100f * 0.7f + 0.3f) * 0.42f).coerceAtLeast(1.2f)
        val filamentWeightGrams = filamentUsageMeters * 3.05f * (config.filamentType.densityGPerCm3 / 1.24f)
        val estimatedMinutes = (totalLayers * 0.85f * (50f / config.printSpeedMmS.coerceAtLeast(20)) + (filamentUsageMeters * 3.5f)).toInt().coerceAtLeast(12)

        val result = GcodeResult(
            id = "CR10S_" + System.currentTimeMillis().toString().takeLast(6),
            projectName = mesh.name,
            printerTarget = config.printerName,
            filamentUsedType = config.filamentType.name,
            layerHeightMm = config.layerHeightMm,
            totalLayers = totalLayers,
            estimatedPrintTimeMinutes = estimatedMinutes,
            estimatedFilamentLengthMeters = filamentUsageMeters,
            estimatedFilamentWeightGrams = filamentWeightGrams,
            estimatedCostEur = filamentWeightGrams * 0.024f,
            fileSizeBytes = gcodeText.toByteArray().size.toLong(),
            gcodeHeaderSnippet = gcodeText.lineSequence().take(35).joinToString("\n"),
            fullGcodeContent = gcodeText,
            slicerEngineUsed = engineName
        )

        emit(SlicingProgress.Completed(result))
    }

    private fun generateFullGcode(mesh: Mesh3D, config: SlicingConfig, totalLayers: Int): String {
        val sb = StringBuilder()

        // 1. Header with metadata
        sb.appendLine("; ==========================================================")
        sb.appendLine("; Generated by Sandros Print Labor")
        sb.appendLine("; Target 3D Printer: Creality CR-10S Pro (Marlin 2.0 / Touchscreen)")
        sb.appendLine("; Object: ${mesh.name}")
        sb.appendLine("; Build Volume: 300 x 300 x 400 mm")
        sb.appendLine("; Filament: ${config.filamentType.displayName} 1.75mm")
        sb.appendLine("; Nozzle Diameter: ${config.nozzleDiameterMm} mm")
        sb.appendLine("; Layer Height: ${config.layerHeightMm} mm (First Layer: ${config.initialLayerHeightMm} mm)")
        sb.appendLine("; Infill: ${config.infillDensityPercent}% [${config.infillPattern.name}]")
        sb.appendLine("; Print Speed: ${config.printSpeedMmS} mm/s (Wall: ${config.outerWallSpeedMmS} mm/s)")
        sb.appendLine("; Nozzle Temp: ${config.nozzleTempC}°C | Bed Temp: ${config.bedTempC}°C")
        sb.appendLine("; Total Layers: $totalLayers")
        sb.appendLine("; ==========================================================")
        sb.appendLine()

        // 2. Machine acceleration & jerk setup for CR-10S Pro
        sb.appendLine("M201 X500.00 Y500.00 Z100.00 E5000.00 ;CR-10S Pro max acceleration")
        sb.appendLine("M203 X500.00 Y500.00 Z10.00 E50.00 ;CR-10S Pro max feedrates")
        sb.appendLine("M204 P500.00 R1000.00 T500.00 ;Print & Retract acceleration")
        sb.appendLine("M205 X8.00 Y8.00 Z0.40 E5.00 ;Jerk limits")
        sb.appendLine("M220 S100 ;Reset Feedrate")
        sb.appendLine("M221 S100 ;Reset Flowrate")
        sb.appendLine()

        // 3. Preheating
        sb.appendLine("M140 S${config.bedTempC} ;Set bed temperature")
        sb.appendLine("M104 S${config.nozzleTempC} ;Set nozzle temperature")
        sb.appendLine("G90 ;Absolute positioning")
        sb.appendLine("M82 ;Absolute extruder coordinates")
        sb.appendLine("G28 ;Home all axes")
        sb.appendLine("G29 ;CR-10S Pro Matrix Auto Bed Leveling")
        sb.appendLine("M420 S1 Z2 ;Enable leveling mesh compensation")
        sb.appendLine("G1 Z5.0 F3000 ;Raise Z")
        sb.appendLine("G1 X0.1 Y20 F5000.0 ;Move to priming start position")
        sb.appendLine("M190 S${config.bedTempC} ;Wait for bed temp")
        sb.appendLine("M109 S${config.nozzleTempC} ;Wait for nozzle temp")
        sb.appendLine()

        // 4. Priming sequence (CR-10S Pro purge line along left bed edge)
        sb.appendLine("; --- CR-10S Pro Purge Line ---")
        sb.appendLine("G92 E0 ;Reset extruder")
        sb.appendLine("G1 Z0.28 F3000 ;Drop to purge height")
        sb.appendLine("G1 X0.1 Y200.0 Z0.28 F1500.0 E15.0 ;First purge stripe")
        sb.appendLine("G1 X0.4 Y200.0 Z0.28 F5000.0 ;Step over")
        sb.appendLine("G1 X0.4 Y20.0 Z0.28 F1500.0 E30.0 ;Second purge stripe")
        sb.appendLine("G92 E0 ;Reset extruder")
        sb.appendLine("G1 E-${config.retractionDistanceMm} F${(config.retractionSpeedMmS * 60).toInt()} ;Pre-print retraction")
        sb.appendLine("G1 Z2.0 F3000 ;Clear bed")
        sb.appendLine()

        // Center on 300x300 bed: center is (150, 150)
        val centerX = 150f + mesh.offsetX
        val centerY = 150f + mesh.offsetY
        val halfW = (mesh.sizeX / 2f).coerceAtLeast(5f)
        val halfD = (mesh.sizeY / 2f).coerceAtLeast(5f)

        var totalE = 0f

        // 5. Generate layer toolpaths
        val sampleLayerCount = totalLayers.coerceAtMost(25) // Generate detailed first N layers
        for (layer in 0 until sampleLayerCount) {
            val z = config.initialLayerHeightMm + (layer * config.layerHeightMm)
            sb.appendLine("; ----------------------------------------")
            sb.appendLine("; LAYER:$layer  Z=%.2f mm".format(z))
            sb.appendLine("; ----------------------------------------")

            if (layer == 0) {
                sb.appendLine("M106 S0 ;Fan off on first layer for bed adhesion")
            } else if (layer == 1) {
                sb.appendLine("M106 S${(config.fanSpeedPercent * 2.55f).toInt()} ;Fan on")
            }

            // Rapid travel to object corner
            sb.appendLine("G0 F${config.travelSpeedMmS * 60} X%.2f Y%.2f Z%.2f".format(centerX - halfW, centerY - halfD, z))
            // Un-retract
            totalE += config.retractionDistanceMm
            sb.appendLine("G1 F${(config.retractionSpeedMmS * 60).toInt()} E%.4f".format(totalE))

            // Outer perimeter rectangle
            val speedFeed = config.outerWallSpeedMmS * 60
            val seg1Len = halfW * 2f
            val seg2Len = halfD * 2f
            val ePerMm = 0.033f * (config.layerHeightMm / 0.2f)

            totalE += seg1Len * ePerMm
            sb.appendLine("G1 F$speedFeed X%.2f Y%.2f E%.4f".format(centerX + halfW, centerY - halfD, totalE))
            totalE += seg2Len * ePerMm
            sb.appendLine("G1 F$speedFeed X%.2f Y%.2f E%.4f".format(centerX + halfW, centerY + halfD, totalE))
            totalE += seg1Len * ePerMm
            sb.appendLine("G1 F$speedFeed X%.2f Y%.2f E%.4f".format(centerX - halfW, centerY + halfD, totalE))
            totalE += seg2Len * ePerMm
            sb.appendLine("G1 F$speedFeed X%.2f Y%.2f E%.4f".format(centerX - halfW, centerY - halfD, totalE))

            // Infill passes (Simulating lines / gyroid infill strokes)
            val infillStep = (4f * (100f / config.infillDensityPercent.coerceAtLeast(10))).coerceIn(2f, 20f)
            var currentY = centerY - halfD + infillStep
            while (currentY < centerY + halfD - 1f) {
                totalE += seg1Len * ePerMm * 0.9f
                sb.appendLine("G1 F${config.printSpeedMmS * 60} X%.2f Y%.2f E%.4f".format(centerX + halfW - 1f, currentY, totalE))
                currentY += infillStep
                if (currentY < centerY + halfD - 1f) {
                    totalE += seg1Len * ePerMm * 0.9f
                    sb.appendLine("G1 F${config.printSpeedMmS * 60} X%.2f Y%.2f E%.4f".format(centerX - halfW + 1f, currentY, totalE))
                }
            }

            // Layer end retract
            totalE -= config.retractionDistanceMm
            sb.appendLine("G1 F${(config.retractionSpeedMmS * 60).toInt()} E%.4f ;Retract".format(totalE))
        }

        if (totalLayers > sampleLayerCount) {
            sb.appendLine("; ... [Schichten $sampleLayerCount bis ${totalLayers - 1} mit identischer Marlin-G-Code-Struktur komprimiert] ...")
        }

        // 6. End G-code for Creality CR-10S Pro
        sb.appendLine()
        sb.appendLine("; --- CR-10S Pro End Script ---")
        sb.appendLine("G91 ;Relative coordinates")
        sb.appendLine("G1 E-2 F2700 ;Retract filament")
        sb.appendLine("G1 E-2 Z0.2 F2400 ;Retract and raise Z")
        sb.appendLine("G1 X5 Y5 F3000 ;Wipe out")
        sb.appendLine("G1 Z10 F2000 ;Raise Z 10mm")
        sb.appendLine("G90 ;Absolute coordinates")
        sb.appendLine("G1 X0 Y300 F3000 ;Present finished part (CR-10S Pro bed forward)")
        sb.appendLine("M106 S0 ;Turn off cooling fan")
        sb.appendLine("M104 S0 ;Turn off nozzle heater")
        sb.appendLine("M140 S0 ;Turn off bed heater")
        sb.appendLine("M84 X Y E ;Disable steppers (keep Z engaged to avoid sag)")
        sb.appendLine("; --- End of G-Code by Sandros Print Labor ---")

        return sb.toString()
    }
}
